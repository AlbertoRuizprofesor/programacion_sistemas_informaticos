#Realizar un programa que lea cuatro valores numéricos e informar su suma y promedio

var1 = int(input ("ingresame el primer valor "))
var2 = int(input ("ingresame el segundo valor "))
var3 = int(input ("ingresame el tercer valor "))
var4 = int(input ("ingresame el cuarto valor "))

suma = var1 + var2 + var3 + var4 
promedio = suma / 4 

print("la suma de los 4 valores es " , suma)
print("el promedo es ", promedio )