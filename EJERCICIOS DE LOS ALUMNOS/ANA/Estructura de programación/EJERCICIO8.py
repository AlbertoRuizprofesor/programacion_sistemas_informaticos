#Calcular el sueldo mensual de un operario conociendo la cantidad de horas trabajadas y el valor por hora

horastrabajadas = int(input ("ingrese las horas trabajadas "))
valorporhora = int(input ("ingrese el importe por hora"))

sueldo = horastrabajadas * valorporhora
print("sueldo a pagar al trabajador es ", sueldo)