#La tupla es una estructura de datos immutable, es decir, no se puede modificar una vez definida
#La tupla, además, permite almacenar cualquier tipo de dato

tupla1 = (1, 2, 3) 
fecha = (25, "Diciembre", 2025) 
punto = (10, 2) 
persona = ("Oliveira", "Carlos", 26)

print("Ejemplos de tuplas")
print(tupla1)
print(fecha)
print(punto)
print(persona)