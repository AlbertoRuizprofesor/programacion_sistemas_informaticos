# Ejercicio 159: Crear un módulo con dos funciones: mayor y menor.
# La función mayor recibe dos números y devuelve el mayor.
# La función menor recibe dos números y devuelve el menor.


def mayor(x1, x2):
    if x1 > x2:
        return x1
    else:
        return x2


def menor(x1, x2):
    if x1 < x2:
        return x1
    else:
        return x2
