#Definir varias tuplas e imprimir sus elementos.

# -----------------------------------------
# Declaración de tuplas
# Cada tupla representa un conjunto fijo de datos.
# -----------------------------------------

numeros = (1, 2, 3)                       # Tupla de números simples
fecha_evento = (25, "Diciembre", 2016)    # Día, mes y año
coordenada = (10, 2)                      # Punto en un plano (x, y)
datos_persona = ("Rodriguez", "Pablo", 43) # Apellido, nombre y edad


# -----------------------------------------
# Impresión de las tuplas
# -----------------------------------------

print(numeros)
print(fecha_evento)
print(coordenada)
print(datos_persona)
