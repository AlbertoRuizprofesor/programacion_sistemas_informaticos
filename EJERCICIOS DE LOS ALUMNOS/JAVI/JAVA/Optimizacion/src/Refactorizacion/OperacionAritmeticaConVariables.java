package Refactorizacion;

public class OperacionAritmeticaConVariables {

    public static void main(String[] args) {
        // Números para la operación
        int primerNumero = 10;
        int segundoNumero = 5;

        // Realizar la suma de los números
        int resultadoSuma = primerNumero + segundoNumero;

        // Mostrar el resultado de la suma
        System.out.println("La suma de " + primerNumero + " y " + segundoNumero + " es: " + resultadoSuma);
    }
}
