#Realizar un programa que imprima en pantalla los números del 0 al 100 con while


#Inicializamos la variable x en 0
x = 0

#Mientras x sea menor que 101, el bucle seguirá ejecutándose
while x < 101:          
    print(x, end = " ") #Imprimimos el valor de x en la misma líena gracias a end = " "
                        #end = " " evita el salto de línea y añade un espacio después de cada número
    x += 1              #Incrementamos x en 1 en cada vuelta de bucle

