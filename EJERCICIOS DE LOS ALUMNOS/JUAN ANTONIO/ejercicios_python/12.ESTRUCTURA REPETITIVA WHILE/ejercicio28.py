#Realizar un programa que imprima en pantalla los números del 1 al 100.


x = 1   #Inicializamos la variable x con el valor 1

#Mientras x sea menor o igual que 100, el bucle seguirá ejecutandose
while x <= 100:
    print(x, end = " ") #Imprime el valor x en la misma línea
    x = x + 1   #Suma uno a la variable 1