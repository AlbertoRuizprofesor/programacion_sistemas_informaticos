#Inicializar un string con la cadena "mAriA" luego llamar a sus métodos upper(), lower() y capitalize(), 
# guardar los datos retornados en otros string y mostrarlos por pantalla.


#Declaración de varible
nombre1 = "mAriA"

#Método .upper() todos los caracteres en mayúsculas
nombre2 = nombre1.upper()

#Método .lower() todos los caracteres en minúsculas
nombre3 = nombre1.lower()

#Método .capitalize() primer caracter en mayúsculas el resto en minúsculas
nombre4 = nombre1.capitalize()

print("Este es el texto original:", nombre1)
print("Este es el método upper():",nombre2)
print("Este es el método lower():",nombre3)
print("Este es el método capitalize():",nombre4)

