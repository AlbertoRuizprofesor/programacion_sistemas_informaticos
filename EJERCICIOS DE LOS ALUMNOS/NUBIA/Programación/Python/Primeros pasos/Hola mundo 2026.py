print("Hola mundo")

numero1 = int(input("Ingresa el primer número: "))
numero2 = int(input("Ingresa el segundo número: "))

Total_suma = numero1 + numero2
Total_resta = numero1 - numero2
Total_multiplicacion = numero1 * numero2
Total_division = numero1 / numero2

print(f"La suma de {numero1} y {numero2} es:", Total_suma)
print(f"La resta de {numero1} y {numero2} es:", Total_resta)
print(f"La multiplicación de {numero1} y {numero2} es:", Total_multiplicacion)
print(f"La división de {numero1} y {numero2} es:", Total_division)